def generate_explanation(route_steps: list, user_goal: str) -> str:
    """
    Генерирует объяснение для всего маршрута (почему он так построен).
    Для MVP используем шаблоны, чтобы демо не упало без интернета.
    """
    if not route_steps:
        return "Не удалось построить маршрут."

    start_title = route_steps[0]["course_title"]
    end_step = route_steps[-1]
    end_title = end_step["course_title"]
    end_price = end_step["price"]

    # Бизнес-логика для текста
    if end_price > 0:
        upsell_text = (
            f"Обратите внимание на финальный шаг: «{end_title}» (стоимость {end_price} руб.). "
            f"Мы рекомендуем его, потому что к этому моменту вы уже освоите базу и будете готовы "
            f"к глубокому погружению. Это наиболее эффективный способ достичь вашей цели."
        )
    else:
        upsell_text = f"Этот маршрут полностью состоит из бесплатных материалов, идеально подходящих для старта."

    explanation = (
        f"Мы построили ваш персональный маршрут на основе цели «{user_goal}». "
        f"Вы начинаете с базового материала «{start_title}», чтобы заложить фундамент. "
        f"Далее сложность плавно возрастает, позволяя вам не потерять мотивацию. "
        f"{upsell_text}"
    )

    return explanation


def generate_step_commentary(step: dict, step_idx: int) -> str:
    """
    Генерирует комментарий к конкретному шагу для красивого таймлайна.
    """
    diff = step["difficulty"]
    is_paid = step["price"] > 0

    if step_idx == 0:
        return "Стартовая точка. Здесь вы заложите базовые знания."
    elif is_paid and step_idx > 0:
        return "Продвинутый уровень. Этот материал даст вам максимальное преимущество для достижения цели."
    elif diff > 0.7:
        return "Глубокое погружение в тему. Отличный шаг для перехода на уровень эксперта."
    else:
        return "Закрепление материала и расширение кругозора по вашей теме."

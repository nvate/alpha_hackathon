import random


# ВАЖНО ДЛЯ ЖЮРИ И РИДМИ:
# В рамках хакатона мы сознательно отказались от интеграции реального API (OpenAI/GigaChat).
# Внешние API добавляют сетевые задержки, риски падения на демо и требуют ключей.
# Вместо этого мы реализовали детерминированный шаблонизатор (Rule-Based LLM Mock).
# В продакшене этот модуль заменяется на 1 вызов API без изменения остальной архитектуры.

def generate_explanation(route_steps: list, user_goal: str) -> str:
    """
    Генерирует общее объяснение маршрута с акцентом на бизнес-ценность.
    """
    if not route_steps:
        return "Не удалось построить маршрут."

    end_step = route_steps[-1]
    end_title = end_step["course_title"]
    end_price = end_step.get("price", 0)

    # Бизнес-логика: если в конце платный курс, делаем акцент на конверсии
    if end_price > 0:
        upsell_text = (
            f"Обратите внимание на финальный шаг: «{end_title}» (стоимость {end_price} руб.). "
            f"Мы рекомендуем его, потому что к этому моменту вы уже освоите базу и будете готовы "
            f"к глубокому погружению. Это наиболее эффективный способ достичь вашей цели."
        )
    else:
        upsell_text = (
            "Этот маршрут состоит из бесплатных материалов, чтобы вы могли начать без инвестиций, "
            "но мы ведем вас к экспертному уровню, где откроются продвинутые инструменты."
        )

    intro = random.choice([
        f"Мы построили ваш персональный маршрут на основе цели «{user_goal}».",
        f"Анализ ваших навыков и цели «{user_goal}» показал, что этот путь будет оптимальным.",
        f"Ваш трек к цели «{user_goal}» сформирован с учетом вашего текущего уровня."
    ])

    explanation = (
        f"{intro} Вы начинаете с базового материала, чтобы заложить фундамент. "
        f"Далее сложность плавно возрастает, позволяя вам не потерять мотивацию. "
        f"{upsell_text}"
    )

    return explanation


def generate_step_commentary(step: dict, step_idx: int, total_steps: int) -> str:
    """
    Генерирует уникальный комментарий к каждому шагу, чтобы таймлайн не выглядел шаблонным.
    """
    diff = step.get("difficulty", 0)
    price = step.get("price", 0)

    # База фраз для разных ситуаций
    intro_frases = ["На этом этапе", "Здесь", "В этом материале", "Сейчас"]
    start_phrases = ["Отличная точка входа.", "Это база, с которой мы начнем."]

    # 1. Первый шаг (Старт)
    if step_idx == 0:
        return random.choice(start_phrases) + " " + random.choice(
            intro_frases) + " вы заложите фундамент, чтобы дальше двигаться увереннее."

    # 2. Финальный шаг (Эксперт / Продажа)
    elif step_idx == total_steps - 1:
        if price > 0:
            return "Финальный шаг. Продвинутый уровень, который окупится вашей экспертизой. Самое время инвестировать в свои знания."
        else:
            return "Финальный шаг. Выход на экспертный уровень. Вы почти у цели!"

    # 3. Платный шаг в середине пути (Кульминация)
    elif price > 0:
        return "Важный переход на новый уровень. Этот материал даст вам конкурентное преимущество и практические инструменты."

    # 4. Обычные шаги в середине (Бесплатные)
    else:
        if diff > 0.7:
            return random.choice(
                intro_frases) + " вы переходите к глубокому погружению в тему. Отличный шаг для прокачки."
        elif diff > 0.4:
            return random.choice(intro_frases) + " вы закрепляете материал и расширяете кругозор по вашей теме."
        else:
            return random.choice(
                intro_frases) + " вы продолжаете знакомиться с базовыми концепциями, необходимыми для вашей цели."